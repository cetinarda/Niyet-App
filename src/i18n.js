export function makeTrans(lang) {
  const d = TRANS[lang] || TRANS.en;
  const fallback = TRANS.en;
  return (key, ...args) => {
    let val = d[key];
    if (val === undefined) val = fallback[key];
    if (typeof val === "function") return val(...args);
    return val ?? key;
  };
}

